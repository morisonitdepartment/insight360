#!/usr/bin/env bash
#
# Builds supabase/GO_LIVE.sql — the two pending migrations and the generated
# seed, concatenated into one file somebody can paste into the Supabase SQL
# editor in a single run.
#
# Three files pasted in the right order is three chances to paste them in the
# wrong one, and a half-applied schema reports itself as "column does not
# exist" from somewhere deep in the seed. One file cannot be mis-ordered.
#
# The expected row counts in the closing check are counted from the seed rather
# than written down, so regenerating the seed with a different number of
# questions cannot leave the check asserting the old one.
#
# Usage:  bash scripts/build-go-live.sh
#
set -euo pipefail

cd "$(dirname "$0")/.."

M10=supabase/migrations/0010_service_sequence.sql
M11=supabase/migrations/0011_brand_framework.sql
SEED=supabase/seed_sterling.sql
OUT=supabase/GO_LIVE.sql

for f in "$M10" "$M11" "$SEED"; do
  [ -f "$f" ] || { echo "missing: $f" >&2; exit 1; }
done

count() { grep -c "insert into public.$1" "$SEED"; }
N_BRANDS=$(count brands)
N_OUTLETS=$(count outlets)
N_TEMPLATES=$(count audit_templates)
N_STAGES=$(count audit_sections)
N_QUESTIONS=$(count audit_questions)

# The seed ends with its own check query. Drop it: this file closes with a
# fuller one, and the SQL editor shows only the last result.
CHECK_LINE=$(grep -n '^-- Check' "$SEED" | head -1 | cut -d: -f1)
SEED_END=$((CHECK_LINE - 1))

{
  cat <<HEADER
-- ===========================================================================
-- GO_LIVE.sql — everything the live database needs, in one run.
--
-- GENERATED by scripts/build-go-live.sh from:
--   $M10
--   $M11
--   $SEED
-- Do not hand-edit. Change a source file and run the script again.
--
-- WHERE: Supabase dashboard -> SQL Editor -> New query -> paste -> Run.
--
-- SAFE TO RE-RUN. Every column is added with \`if not exists\`, every insert
-- updates on conflict instead of duplicating. Running it twice changes nothing
-- the second time, so a half-finished run is fixed by running it again.
--
-- It does NOT touch visits, answers, evidence or anything a shopper records.
-- It installs the questionnaire and the three outlets, nothing else.
--
-- WHAT IT DOES NOT DO: create the people who sign in. Supabase Auth owns
-- passwords, so each shopper must be added under Authentication -> Users
-- first, and then supabase/create_shoppers.sql links them to shopper records.
--
-- The last thing it prints is a check. questions must read $N_QUESTIONS.
-- ===========================================================================

-- Stop early with a clear message rather than a wall of errors if the base
-- schema was never installed.
do \$\$
begin
  if to_regclass('public.audit_questions') is null then
    raise exception 'Base schema missing. Run migrations 0001-0009 first, then this file.';
  end if;
end \$\$;


-- ===========================================================================
-- PART 1 of 3 — migration 0010: the service-sequence engine
-- ===========================================================================
HEADER
  cat "$M10"
  cat <<'MID'


-- ===========================================================================
-- PART 2 of 3 — migration 0011: brand frameworks
-- ===========================================================================
MID
  cat "$M11"
  cat <<'MID2'


-- ===========================================================================
-- PART 3 of 3 — the questionnaire, the brands and the three outlets
-- ===========================================================================
MID2
  sed -n "1,${SEED_END}p" "$SEED"
  cat <<FOOTER

-- ===========================================================================
-- CHECK — read every row. Anything marked FAIL means the run did not finish.
-- ===========================================================================
select
  label,
  actual,
  expected,
  case when actual = expected then 'OK' else 'FAIL' end as result
from (
  values
    ('brands',    (select count(*) from public.brands),          ${N_BRANDS}::bigint),
    ('outlets',   (select count(*) from public.outlets),         ${N_OUTLETS}::bigint),
    ('templates', (select count(*) from public.audit_templates), ${N_TEMPLATES}::bigint),
    ('stages',    (select count(*) from public.audit_sections),  ${N_STAGES}::bigint),
    ('questions', (select count(*) from public.audit_questions), ${N_QUESTIONS}::bigint)
) as t(label, actual, expected);
FOOTER
} > "$OUT"

echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
echo "  brands $N_BRANDS · outlets $N_OUTLETS · templates $N_TEMPLATES · stages $N_STAGES · questions $N_QUESTIONS"
