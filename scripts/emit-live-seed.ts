/*
 * Emits the live-mode seed for the current client as a single SQL file.
 *
 * The demo builds its brands, outlets, templates, sections, questions, shoppers
 * and opening visits in code. Live Mode needs the same rows in Postgres. Rather
 * than transcribe 562 questions by hand, this reads the app's own dataset and
 * writes the INSERTs, so the live database and the demonstration cannot drift.
 *
 *   VITE_APP_MODE=demo VITE_CLIENT=sterling npm run emit:live-seed
 *
 * Output: supabase/seed_<client>.sql — idempotent (on conflict do update), so it
 * is safe to re-run after a questionnaire change.
 *
 * Requires migrations 0010 and 0011: the sequence, stage_weight, kpi_keys,
 * derived_from, comment_on_fail and clock columns do not exist without them.
 */
import { writeFileSync } from 'node:fs'
import { buildTemplates } from '@/data/templates'
import { emptyDataset, generateDataset, portfolioDataset } from '@/data/seed'
import { CLIENT } from '@/config/client'

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  return `'${String(v).replace(/'/g, "''")}'`
}
/** A Postgres text[] literal, or null. */
const arr = (v: readonly string[] | undefined | null): string =>
  v && v.length ? `array[${v.map(q).join(',')}]::text[]` : 'null'
/** A jsonb literal, or null. */
const json = (v: unknown): string => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`)

// The same dataset the demonstration opens with, so the live questionnaire and
// the one the client has been shown are the same rows.
const seedMode = CLIENT.demoSeed ?? 'full'
const ds = seedMode === 'portfolio' ? portfolioDataset() : seedMode === 'empty' ? emptyDataset() : generateDataset()
const { templates, sections, questions } = buildTemplates()

const lines: string[] = []
const say = (s = '') => lines.push(s)

say('-- ===========================================================================')
say(`-- seed_${CLIENT.id}.sql — the live-mode questionnaire and opening schedule.`)
say('--')
say('-- GENERATED by scripts/emit-live-seed.ts. Do not hand-edit: change the client')
say('-- profile or the template and run the generator again.')
say('--')
say('-- Apply migrations 0010_service_sequence.sql and 0011_brand_framework.sql')
say('-- FIRST. Without them this file fails on a missing column.')
say('--')
say('-- Safe to re-run: every insert updates on conflict rather than duplicating.')
say('-- ===========================================================================')
say()
say('begin;')
say()

// ── brands ────────────────────────────────────────────────────────────────
say('-- Brands ---------------------------------------------------------------')
for (const b of ds.brands) {
  say(
    `insert into public.brands (id, name, segment, outlet_count, template_code) values (${q(b.id)}, ${q(b.name)}, ${q(b.segment)}, ${b.outletCount}, ${q(b.templateCode ?? null)})\n` +
      `  on conflict (id) do update set name = excluded.name, segment = excluded.segment, outlet_count = excluded.outlet_count, template_code = excluded.template_code;`,
  )
}
say()

// ── outlets ───────────────────────────────────────────────────────────────
say('-- Outlets --------------------------------------------------------------')
for (const o of ds.outlets) {
  say(
    `insert into public.outlets (id, code, name, brand_id, brand, segment, subcategory, location, region, manager, status, opening_hours, target_score, annual_visits, map_x, map_y, next_audit)\n` +
      `  values (${q(o.id)}, ${q(o.code)}, ${q(o.name)}, ${q(o.brandId)}, ${q(o.brand)}, ${q(o.segment)}, ${q(o.subcategory)}, ${q(o.location)}, ${q(o.region)}, ${q(o.manager)}, ${q(o.status)}, ${q(o.openingHours)}, ${o.targetScore}, ${o.annualVisits}, ${o.mapX}, ${o.mapY}, ${q(o.nextAudit)})\n` +
      `  on conflict (id) do update set code = excluded.code, name = excluded.name, brand_id = excluded.brand_id, brand = excluded.brand, segment = excluded.segment, subcategory = excluded.subcategory, location = excluded.location, region = excluded.region, manager = excluded.manager, status = excluded.status, opening_hours = excluded.opening_hours, target_score = excluded.target_score, annual_visits = excluded.annual_visits, map_x = excluded.map_x, map_y = excluded.map_y, next_audit = excluded.next_audit;`,
  )
}
say()

// ── templates ─────────────────────────────────────────────────────────────
say('-- Questionnaires -------------------------------------------------------')
for (const t of templates) {
  say(
    `insert into public.audit_templates (id, name, code, description, segment, journey, version, status, section_ids, question_count, is_follow_up, sequence)\n` +
      `  values (${q(t.id)}, ${q(t.name)}, ${q(t.code)}, ${q(t.description)}, ${q(t.segment)}, ${q(t.journey)}, ${q(t.version)}, ${q(t.status)}, ${arr(t.sectionIds)}, ${t.questionCount}, ${t.isFollowUp}, ${json(t.sequence ?? null)})\n` +
      `  on conflict (id) do update set name = excluded.name, code = excluded.code, description = excluded.description, segment = excluded.segment, journey = excluded.journey, version = excluded.version, status = excluded.status, section_ids = excluded.section_ids, question_count = excluded.question_count, is_follow_up = excluded.is_follow_up, sequence = excluded.sequence;`,
  )
}
say()

say('-- Stages ---------------------------------------------------------------')
for (const [i, s] of sections.entries()) {
  say(
    `insert into public.audit_sections (id, template_id, code, title, category, description, "order", applicable_to, stage_weight, kpi_name)\n` +
      `  values (${q(s.id)}, ${q(s.templateId)}, ${q(s.code)}, ${q(s.title)}, ${q(s.category)}, ${q(s.description)}, ${s.order ?? i}, ${json(s.applicableTo)}, ${s.stageWeight ?? 'null'}, ${q(s.kpiName ?? null)})\n` +
      `  on conflict (id) do update set template_id = excluded.template_id, code = excluded.code, title = excluded.title, category = excluded.category, description = excluded.description, "order" = excluded."order", applicable_to = excluded.applicable_to, stage_weight = excluded.stage_weight, kpi_name = excluded.kpi_name;`,
  )
}
say()

say('-- Questions ------------------------------------------------------------')
for (const [i, qn] of questions.entries()) {
  say(
    `insert into public.audit_questions (id, section_id, code, text, type, weight, critical, evidence_required, comment_required, allow_na, guidance, options, threshold, "order", kpi_keys, timing_role, condition, derived_from, comment_on_fail, required)\n` +
      `  values (${q(qn.id)}, ${q(qn.sectionId)}, ${q(qn.code)}, ${q(qn.text)}, ${q(qn.type)}, ${qn.weight}, ${qn.critical}, ${qn.evidenceRequired}, ${qn.commentRequired}, ${qn.allowNA}, ${q(qn.guidance ?? '')}, ${arr(qn.options)}, ${qn.threshold ?? 'null'}, ${qn.order ?? i}, ${arr(qn.kpiKeys)}, ${q(qn.timingRole ?? null)}, ${json(qn.condition ?? null)}, ${json(qn.derivedFrom ?? null)}, ${qn.commentOnFail ?? false}, ${qn.required ?? false})\n` +
      `  on conflict (id) do update set section_id = excluded.section_id, code = excluded.code, text = excluded.text, type = excluded.type, weight = excluded.weight, critical = excluded.critical, evidence_required = excluded.evidence_required, comment_required = excluded.comment_required, allow_na = excluded.allow_na, guidance = excluded.guidance, options = excluded.options, threshold = excluded.threshold, "order" = excluded."order", kpi_keys = excluded.kpi_keys, timing_role = excluded.timing_role, condition = excluded.condition, derived_from = excluded.derived_from, comment_on_fail = excluded.comment_on_fail, required = excluded.required;`,
  )
}
say()

say('commit;')
say()
say('-- Check ----------------------------------------------------------------')
say("select 'brands' t, count(*) n from public.brands")
say("union all select 'outlets', count(*) from public.outlets")
say("union all select 'templates', count(*) from public.audit_templates")
say("union all select 'stages', count(*) from public.audit_sections")
say("union all select 'questions', count(*) from public.audit_questions order by t;")

const out = `supabase/seed_${CLIENT.id}.sql`
writeFileSync(out, lines.join('\n') + '\n', 'utf8')
console.log(
  `${out}: ${ds.brands.length} brands, ${ds.outlets.length} outlets, ${templates.length} templates, ${sections.length} stages, ${questions.length} questions`,
)
